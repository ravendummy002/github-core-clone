/** Encode one data packet: 4 hex length bytes (payload + 4) then the payload. */
export function pktLine(payload: string | Uint8Array): Buffer {
  const data = typeof payload === 'string' ? Buffer.from(payload, 'utf8') : Buffer.from(payload);
  if (data.length > PKT_LINE_MAX - 4) throw new Error('pkt-line payload is too long');
  const header = Buffer.allocUnsafe(4);
  header.write((data.length + 4).toString(16).padStart(4, '0'), 0, 4, 'ascii');
  return Buffer.concat([header, data]);
}

export const PKT_FLUSH = Buffer.from('0000', 'ascii');
export const PKT_DELIM = Buffer.from('0001', 'ascii');
export const PKT_RESPONSE_END = Buffer.from('0002', 'ascii');

/** Encode a mixed sequence; 'flush'/'delim'/'response-end' are the control packets. */
export function pktLines(items: ReadonlyArray<string | Uint8Array | 'flush' | 'delim' | 'response-end'>): Buffer {
  const parts: Buffer[] = [];
  for (const item of items) {
    if (item === 'flush') parts.push(PKT_FLUSH);
    else if (item === 'delim') parts.push(PKT_DELIM);
    else if (item === 'response-end') parts.push(PKT_RESPONSE_END);
    else parts.push(pktLine(item));
  }
  return Buffer.concat(parts);
}

export type Packet =
  | { kind: 'data'; payload: Buffer }
  | { kind: 'flush' }
  | { kind: 'delim' }
  | { kind: 'response-end' };

/** Decode a complete buffer into packets. `stopAtRaw` stops before bytes that are not a pkt-line header (a pack). */
export function decodePktLines(bytes: Uint8Array, options: { stopAtRaw?: boolean } = {}): { packets: Packet[]; rest: Buffer } {
  const buffer = Buffer.isBuffer(bytes) ? bytes : Buffer.from(bytes);
  const packets: Packet[] = [];
  let offset = 0;
  while (offset + 4 <= buffer.length) {
    const header = buffer.subarray(offset, offset + 4).toString('ascii');
    if (!/^[0-9a-fA-F]{4}$/.test(header)) {
      if (options.stopAtRaw === true) break;
      throw new Error(`invalid pkt-line length ${JSON.stringify(header)}`);
    }
    const length = Number.parseInt(header, 16);
    if (length === 0) {
      packets.push({ kind: 'flush' });
      offset += 4;
      continue;
    }
    if (length === 1) {
      packets.push({ kind: 'delim' });
      offset += 4;
      continue;
    }
    if (length === 2) {
      packets.push({ kind: 'response-end' });
      offset += 4;
      continue;
    }
    if (length < 4 || length > PKT_LINE_MAX) throw new Error(`invalid pkt-line length ${length}`);
    if (offset + length > buffer.length) throw new Error('truncated pkt-line');
    packets.push({ kind: 'data', payload: buffer.subarray(offset + 4, offset + length) });
    offset += length;
  }
  return { packets, rest: buffer.subarray(offset) };
}

/** Split data packets of a sideband stream into band-1 payload, progress text and errors. */
export function demuxSideband(packets: readonly Packet[]): { pack: Buffer; progress: string } {
  const chunks: Buffer[] = [];
  let progress = '';
  for (const packet of packets) {
    if (packet.kind !== 'data' || packet.payload.length < 1) continue;
    const band = packet.payload[0] as number;
    if (band === 1) chunks.push(packet.payload.subarray(1));
    else if (band === 2) progress += packet.payload.subarray(1).toString('utf8');
    else if (band === 3) throw new Error(`sideband error: ${packet.payload.subarray(1).toString('utf8').trim()}`);
  }
  return { pack: Buffer.concat(chunks), progress };
}

/** Frame bytes as sideband band-1 packets, each at most the pkt-line maximum. */
export function sidebandPack(pack: Buffer): Buffer[] {
  const out: Buffer[] = [];
  const maxPayload = PKT_LINE_MAX - 4 - 1; // header + band byte
  for (let offset = 0; offset < pack.length; offset += maxPayload) {
    const chunk = pack.subarray(offset, Math.min(pack.length, offset + maxPayload));
    out.push(pktLine(Buffer.concat([Buffer.from([1]), chunk])));
  }
  if (out.length === 0) out.push(pktLine(Buffer.from([1])));
  return out;
}
